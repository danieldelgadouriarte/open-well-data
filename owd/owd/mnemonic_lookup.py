"""Mnemonic lookup: what a channel name (HKLA, RS, DEPTH...) means, with the evidence behind it.

Reads, at call time, the dictionary files kept by the pipeline (they are regenerated by owd/pipeline):
  variables.tsv                  variables, units, families and their mnemonics
  data/mnemonic_evidence.csv     one row per mnemonic and variable, with status and what the files showed
  data/mnemonic_conflicts.csv    mnemonics with several meanings, resolved by context or open
  data/mnemonic_context.csv      context rules (via mnemonic_context.py)

lookup(mnemonic, unit="", source_format="") -> dict for one mnemonic.
variants(variable) -> every mnemonic of a variable with its statistic (hookload: HKLD, HKLD_MIN, HKLX...).
entries() -> list of compact dicts, one per mnemonic, for the site (data/mnemonics.json).
Standard library only.

Statistic (7 Nov 2026): the evidence rows carry `statistic` and `window` (columns of mnemonic_evidence.csv, from the
rules of channel_statistics.tsv over the recorded descriptions). A value such as "mean|unspecified" means that each
file's own description decides (owd.convert.channel_statistic).
"""
import csv
import os
from collections import defaultdict

from . import mnemonic_context

_DIR = os.path.dirname(os.path.abspath(__file__))
VARIABLES_FILE = os.path.join(_DIR, "variables.tsv")
EVIDENCE_FILE = os.path.join(_DIR, "data", "mnemonic_evidence.csv")
CONFLICTS_FILE = os.path.join(_DIR, "data", "mnemonic_conflicts.csv")

STATUS_LABEL = {
    "verified_by_data": "verified with data",
    "name_only": "name only",
    "conflict": "conflict",
    "unmapped": "seen, not mapped",
    "listed": "listed, not seen in the harvested files",
}


def _split(s):
    return [x for x in (s or "").split("|") if x]


def _descriptions(s):
    out = []
    for d in _split(s):
        d = " ".join(d.split())
        if d and d not in out:
            out.append(d)
    return out


def _int(s):
    try:
        return int(float(s))
    except (TypeError, ValueError):
        return 0


def _num(s):
    try:
        x = float(s)
    except (TypeError, ValueError):
        return None
    return int(x) if x == int(x) and abs(x) < 1e15 else round(x, 6)


def _read(path, delimiter=","):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter=delimiter))


def load():
    """Fresh copy of the dictionary tables: (variables by name, mnemonics listed per variable, evidence by mnemonic,
    conflicts by mnemonic, context rules by mnemonic). Keys are upper-case mnemonics."""
    variables = {v["variable"]: v for v in _read(VARIABLES_FILE, "\t")}
    listed = defaultdict(list)
    for v in variables.values():
        for m in _split(v.get("mnemonics")):
            if v["variable"] not in listed[m.upper()]:
                listed[m.upper()].append(v["variable"])
    evidence = defaultdict(list)
    for r in _read(EVIDENCE_FILE):
        evidence[r["mnemonic"].strip().upper()].append(r)
    conflicts = defaultdict(list)
    for r in _read(CONFLICTS_FILE):
        conflicts[r["mnemonic"].strip().upper()].append(r)
    context = mnemonic_context.load_context()
    return variables, listed, evidence, conflicts, context


def _variable_info(variables, name):
    v = variables.get(name) or {}
    return {"variable": name, "unit": v.get("unit", ""), "family": v.get("family", ""),
            "dimension": v.get("dimension", ""), "description": v.get("description", ""),
            "standard_channel": v.get("standard_channel", "") == "yes"}


def _evidence(r):
    datasets, companies = _split(r.get("datasets")), _split(r.get("companies"))
    out = {"variable": r.get("variable") or "", "status": r.get("status") or "",
           "status_label": STATUS_LABEL.get(r.get("status"), r.get("status") or ""),
           "conflict_type": r.get("conflict_type") or "", "mapped_by": r.get("method") or "",
           "n_files": _int(r.get("n_files")), "n_wells": _int(r.get("n_wells")),
           "n_datasets": len(datasets), "n_companies": len(companies), "datasets": datasets, "companies": companies,
           "declared_units": _split(r.get("units")), "descriptions": _descriptions(r.get("descriptions"))[:6],
           "variable_unit": r.get("variable_unit") or "",
           "typical_range": None, "files_in_range": _int(r.get("n_range_pass")),
           "files_out_of_range": _int(r.get("n_range_fail")), "note": r.get("note") or "",
           "statistic": "", "window": ""}
    if out["variable"]:
        st, win = r.get("statistic"), r.get("window")
        if st is None:      # an evidence file written before the statistic columns
            from .convert import dictionary_statistic
            st, win = dictionary_statistic(r.get("mnemonic") or "", out["variable"], _descriptions(r.get("descriptions"))[:3])
        out["statistic"], out["window"] = st or "", win or ""
    p01, p50, p99 = _num(r.get("typ_p01")), _num(r.get("typ_p50")), _num(r.get("typ_p99"))
    if p50 is not None:
        out["typical_range"] = {"p01": p01, "p50": p50, "p99": p99, "unit": out["variable_unit"]}
    return out


def _conflict(r):
    return {"type": r.get("conflict_type") or "", "source_formats": r.get("source_formats") or "",
            "resolution": r.get("resolution") or "", "variable": r.get("meaning_variable") or "",
            "unit_dimension": r.get("unit_dimension") or "", "units": r.get("units") or "",
            "descriptions": r.get("descriptions") or "", "datasets": _split(r.get("datasets")),
            "n_files": _int(r.get("n_files"))}


def _rule(r):
    return {"when_unit_dimension": r.get("when_unit_dimension") or "any", "when_source": r.get("when_source") or "any",
            "variable": r.get("variable") or "", "note": r.get("note") or ""}


def lookup(mnemonic, unit="", source_format="", tables=None):
    """Meaning of a mnemonic. `unit`: the unit declared in the file (e.g. "ohm.m", "klbs"); `source_format`: LAS, DLIS,
    LIS, WITSML (log files) or anything else (a table, e.g. "PVT"). Both are optional; they only matter for mnemonics
    with a context rule (RS, Rw, BHT, DEPTH, TIME, MFOP...)."""
    variables, listed, evidence, conflicts, context = tables or load()
    key = str(mnemonic or "").strip().upper()
    ev = [_evidence(r) for r in evidence.get(key, [])]
    rules = [_rule(r) for r in context.get(key, [])]
    out = {"mnemonic": key, "found": bool(ev or listed.get(key) or rules), "variable": "", "status": "",
           "how": "", "context_rule": None, "candidates": [], "evidence": ev, "context_rules": rules,
           "conflicts": [_conflict(r) for r in conflicts.get(key, [])], "listed_under": listed.get(key, [])}
    if not out["found"]:
        out["how"] = "not in the dictionary and not seen in the harvested files"
        return out
    mapped = [e for e in ev if e["variable"]]
    cands = []
    for name in [e["variable"] for e in mapped] + listed.get(key, []) + [r["variable"] for r in rules]:
        if name and name not in cands:
            cands.append(name)
    out["candidates"] = cands
    if rules and (unit or source_format):
        dim = mnemonic_context.unit_dimension(unit)
        fmt = (source_format or "").upper()
        var = mnemonic_context.context_rule(key, dim, fmt, context)
        if var:
            hit = next(r for r in context[key] if r["variable"] == var and mnemonic_context.context_rule(key, dim, fmt, {key: [r]}))
            out["variable"], out["how"] = var, "context rule"
            out["context_rule"] = {**_rule(hit), "unit": unit, "unit_dimension": dim or "unknown",
                                   "source_format": fmt or "table"}
    elif rules:
        out["how"] = "depends on context: pass the declared unit and/or the source format (LAS, DLIS, LIS, WITSML or a table)"
    elif len(cands) == 1:
        out["variable"] = cands[0]
        out["how"] = "evidence" if mapped else "listed in variables.tsv"
    elif len(cands) > 1:
        out["how"] = "several variables: see candidates and conflicts"
    else:
        out["how"] = "seen in the files but not mapped to a variable"
    chosen = next((e for e in ev if out["variable"] and e["variable"] == out["variable"]), None)
    out["statistic"], out["window"] = "", ""
    if out["variable"]:
        if chosen:
            out["statistic"], out["window"] = chosen["statistic"], chosen["window"]
        else:
            from .convert import dictionary_statistic
            out["statistic"], out["window"] = dictionary_statistic(key, out["variable"])
    if chosen:
        out["status"] = chosen["status"]
    elif out["variable"] and key in listed:
        out["status"] = "listed"
    elif ev and not mapped:
        out["status"] = ev[0]["status"] or "unmapped"
    elif any(e["status"] == "conflict" for e in ev):
        out["status"] = "conflict"
    out["status_label"] = STATUS_LABEL.get(out["status"], out["status"])
    out["variable_info"] = _variable_info(variables, out["variable"]) if out["variable"] else None
    out["candidate_info"] = [_variable_info(variables, c) for c in cands]
    return out


def entries(tables=None):
    """One compact dict per mnemonic (evidence rows, mnemonics listed in variables.tsv, context rules), for the site.
    Keys: m mnemonic, r rows [{v variable, s status, f files, w wells, d datasets, c companies, u declared units,
    t typical range [p01, p50, p99] in the variable unit, x descriptions, n note, k conflict type, st statistic,
    wn window}], ctx rules,
    cf conflicts, l variables listing the mnemonic."""
    variables, listed, evidence, conflicts, context = tables or load()
    out = []
    for key in sorted(set(evidence) | set(listed) | set(context)):
        rows = []
        for r in evidence.get(key, []):
            e = _evidence(r)
            row = {"v": e["variable"], "s": e["status"], "f": e["n_files"], "w": e["n_wells"], "d": e["datasets"],
                   "c": e["companies"], "u": e["declared_units"][:8], "x": e["descriptions"][:3]}
            if e["typical_range"]:
                t = e["typical_range"]
                row["t"] = [t["p01"], t["p50"], t["p99"]]
            if e["conflict_type"]:
                row["k"] = e["conflict_type"]
            if e["statistic"]:
                row["st"] = e["statistic"]
            if e["window"]:
                row["wn"] = e["window"]
            if e["note"] and e["status"] != "unmapped":
                row["n"] = e["note"]
            rows.append({k: v for k, v in row.items() if v not in ("", [], None)})
        seen = {r.get("v") for r in rows}
        for name in listed.get(key, []):
            if name not in seen:
                rows.append({"v": name, "s": "listed"})
        ent = {"m": key, "r": rows}
        if context.get(key):
            ent["ctx"] = [[r["when_unit_dimension"] or "any", r["when_source"] or "any", r["variable"], r["note"]] for r in context[key]]
        if conflicts.get(key):
            ent["cf"] = [[r["conflict_type"], r["source_formats"], r["meaning_variable"], r["units"], r["descriptions"],
                          r["resolution"], _int(r["n_files"])] for r in conflicts[key]]
        out.append(ent)
    return out


def variants(variable, tables=None):
    """Every mnemonic of a variable (listed in variables.tsv or seen in the files) with its statistic, so that a search
    for hookload finds HKLD, HKLD_MIN, HKLX... and says which is the mean, the maximum or the minimum.
    One dict per mnemonic: mnemonic, statistic, window, output_names (hookload, hookload_max...), status, n_files."""
    from .convert import dictionary_statistic, qualified_name
    variables, listed, evidence, conflicts, context = tables or load()
    out = []
    keys = sorted({k for k, vs in listed.items() if variable in vs} |
                  {k for k, rows in evidence.items() if any((r.get("variable") or "") == variable for r in rows)})
    for key in keys:
        r = next((x for x in evidence.get(key, []) if (x.get("variable") or "") == variable), None)
        e = _evidence(r) if r else None
        st, win = (e["statistic"], e["window"]) if e else dictionary_statistic(key, variable)
        # drilling and mud_gas carry the statistic in the name; other families only when two statistics of the
        # variable coexist in a file (owd.convert.naming_statistics), so their usual name is the plain one
        qual = (variables.get(variable) or {}).get("family") in _qualify_families()
        names = ([qualified_name(variable, s) for s in _split(st)] if qual else []) or [variable]
        out.append({"mnemonic": key, "statistic": st or "unspecified", "window": win,
                    "output_names": list(dict.fromkeys(names)), "status": e["status"] if e else "listed",
                    "n_files": e["n_files"] if e else 0})
    return out


def _qualify_families():
    from .convert import index
    return {r["pattern"] for r in index().t.get("statistics", []) if r["kind"] == "qualify_family"}


def variable_table(tables=None):
    """{variable: [unit, family, description]} for every variable in variables.tsv."""
    variables = (tables or load())[0]
    return {k: [v.get("unit", ""), v.get("family", ""), v.get("description", "")] for k, v in variables.items()}
